#!/usr/bin/env python3
"""
Reconstruct noisy Arabic Whisper transcripts, convert their intended meaning
to Modern Standard Arabic, and translate them using a local Ollama model.

Input:
    A JSON file generated by the faster-whisper transcription script.

Expected input structure:
{
    "segments": [
        {
            "id": 0,
            "start": 0.0,
            "end": 4.5,
            "text": "..."
        }
    ]
}

Outputs:
    <name>.semantic.json
    <name>.reconstructed_arabic.txt
    <name>.msa.txt
    <name>.translation.txt
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ollama import Client, ResponseError
from pydantic import BaseModel, Field, ValidationError


# ---------------------------------------------------------------------------
# Structured model output
# ---------------------------------------------------------------------------

class UncertainSpan(BaseModel):
    raw_text: str = Field(
        description="The unclear or doubtful wording from the ASR transcript."
    )
    possible_interpretations: list[str] = Field(
        default_factory=list,
        description="Plausible interpretations, when available."
    )
    explanation: str = Field(
        description="A short explanation of why this wording is uncertain."
    )


class SemanticOutput(BaseModel):
    reconstructed_arabic: str = Field(
        description=(
            "The most probable original spoken Arabic after repairing clear "
            "ASR errors. Preserve tone, dialectal character, rhetorical "
            "questions, emphasis, religious expressions, names and numbers."
        )
    )

    msa: str = Field(
        description=(
            "A complete, meaning-faithful Modern Standard Arabic rendering. "
            "It may repair broken spoken syntax, but it must not summarize, "
            "soften, intensify or add information."
        )
    )

    translation: str = Field(
        description=(
            "A fluent and complete translation of the intended meaning into "
            "the requested target language."
        )
    )

    uncertain_spans: list[UncertainSpan] = Field(default_factory=list)

    needs_review: bool = Field(
        description=(
            "True when part of the passage cannot be reconstructed or "
            "translated confidently."
        )
    )


# ---------------------------------------------------------------------------
# Internal transcript structures
# ---------------------------------------------------------------------------

@dataclass
class WhisperSegment:
    segment_id: int
    start: float
    end: float
    text: str


@dataclass
class TranscriptChunk:
    chunk_id: int
    segments: list[WhisperSegment]

    @property
    def start(self) -> float:
        return self.segments[0].start

    @property
    def end(self) -> float:
        return self.segments[-1].end

    @property
    def raw_text(self) -> str:
        return "\n".join(
            segment.text.strip()
            for segment in self.segments
            if segment.text.strip()
        )

    @property
    def segment_ids(self) -> list[int]:
        return [segment.segment_id for segment in self.segments]


# ---------------------------------------------------------------------------
# Prompt
# ---------------------------------------------------------------------------

SYSTEM_PROMPT = """
You are an expert Arabic transcript reconstruction and translation system.

Your input is a noisy automatic speech recognition transcript. The speaker may
use Palestinian, Levantine, Egyptian, Gulf, Iraqi, Maghrebi, or mixed Arabic.
The ASR may contain phonetically similar substitutions, missing words, broken
word boundaries, corrupted names, incorrect negation, and missing punctuation.

Your primary goal is to recover the speaker's intended meaning accurately.

Produce exactly three main textual outputs:

1. reconstructed_arabic:
   Reconstruct the most probable Arabic wording that was actually spoken.
   Repair clear ASR errors using the whole passage as context. Keep the
   speaker's emotional force, dialectal character, rhetorical questions,
   repetitions used for emphasis, religious expressions, profanity,
   political language, and code-switching.

2. msa:
   Express the complete intended meaning in clear Modern Standard Arabic.
   Repair fragmented spoken syntax where necessary. Preserve all meaningful
   details, claims, uncertainty, emphasis, negation, names, quantities, dates,
   religious references, and rhetorical structure.

3. translation:
   Translate the intended meaning completely and fluently into the requested
   target language. Translate idioms by meaning rather than word for word.

Strict rules:

- Do not summarize.
- Do not censor or soften the speaker.
- Do not make the speaker more extreme than the source.
- Do not add facts, explanations, background information, or interpretations.
- Do not silently invent missing speech.
- Do not change names, numbers, dates, amounts, places, or organizations
  without strong contextual support.
- Preserve negation carefully.
- Preserve rhetorical questions as questions.
- When a phrase is genuinely unclear, retain the most defensible wording and
  record the uncertainty in uncertain_spans.
- needs_review must be true when an uncertainty could materially change the
  meaning or translation.
- Return only content matching the supplied JSON schema.
""".strip()


# ---------------------------------------------------------------------------
# Arguments
# ---------------------------------------------------------------------------

def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Reconstruct, convert to MSA, and translate a Whisper transcript "
            "using a local Ollama model."
        )
    )

    parser.add_argument(
        "input_json",
        type=Path,
        help="Whisper JSON transcript.",
    )

    parser.add_argument(
        "output_dir",
        type=Path,
        help="Directory for output files.",
    )

    parser.add_argument(
        "--model",
        default="qwen3:8b",
        help="Ollama model. Default: qwen3:8b",
    )

    parser.add_argument(
        "--target-language",
        default="English",
        help="Translation target language. Default: English",
    )

    parser.add_argument(
        "--dialect-hint",
        default="unknown or mixed Arabic",
        help="Optional hint, such as Palestinian Arabic.",
    )

    parser.add_argument(
        "--max-seconds",
        type=float,
        default=45.0,
        help="Approximate maximum duration of each context block.",
    )

    parser.add_argument(
        "--max-words",
        type=int,
        default=220,
        help="Approximate maximum number of transcript words per block.",
    )

    parser.add_argument(
        "--context-segments",
        type=int,
        default=1,
        help=(
            "Number of neighboring segments supplied before and after each "
            "block for context. Default: 1"
        ),
    )

    parser.add_argument(
        "--temperature",
        type=float,
        default=0.1,
        help="Model temperature. Default: 0.1",
    )

    parser.add_argument(
        "--ollama-host",
        default="http://localhost:11434",
        help="Ollama server address.",
    )

    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite an existing semantic JSON output.",
    )

    parser.add_argument(
        "--retries",
        type=int,
        default=2,
        help="Retries following an invalid or failed response.",
    )

    return parser.parse_args()


# ---------------------------------------------------------------------------
# Input handling
# ---------------------------------------------------------------------------

def load_json(path: Path) -> dict[str, Any]:
    try:
        with path.open("r", encoding="utf-8") as file:
            value = json.load(file)
    except FileNotFoundError as exc:
        raise RuntimeError(f"Input file does not exist: {path}") from exc
    except json.JSONDecodeError as exc:
        raise RuntimeError(f"Invalid JSON in {path}: {exc}") from exc

    if not isinstance(value, dict):
        raise RuntimeError("The top-level JSON value must be an object.")

    return value


def extract_segments(payload: dict[str, Any]) -> list[WhisperSegment]:
    raw_segments = payload.get("segments")

    # Support the earlier report format in which the transcription may be
    # nested inside a file record.
    if raw_segments is None and isinstance(payload.get("files"), list):
        files = payload["files"]

        if len(files) == 1 and isinstance(files[0], dict):
            raw_segments = files[0].get("segments")

    if not isinstance(raw_segments, list):
        raise RuntimeError(
            "No 'segments' array was found in the Whisper JSON."
        )

    segments: list[WhisperSegment] = []

    for position, raw in enumerate(raw_segments):
        if not isinstance(raw, dict):
            continue

        text = str(raw.get("text", "")).strip()

        if not text:
            continue

        try:
            segment = WhisperSegment(
                segment_id=int(raw.get("id", position)),
                start=float(raw.get("start", 0.0)),
                end=float(raw.get("end", 0.0)),
                text=text,
            )
        except (TypeError, ValueError) as exc:
            raise RuntimeError(
                f"Invalid segment at array position {position}: {exc}"
            ) from exc

        segments.append(segment)

    if not segments:
        raise RuntimeError("The transcript contains no usable text segments.")

    return segments


# ---------------------------------------------------------------------------
# Chunking
# ---------------------------------------------------------------------------

def count_words(text: str) -> int:
    return len(text.split())


def create_chunks(
    segments: list[WhisperSegment],
    max_seconds: float,
    max_words: int,
) -> list[TranscriptChunk]:
    chunks: list[TranscriptChunk] = []
    current: list[WhisperSegment] = []
    current_words = 0

    for segment in segments:
        segment_words = count_words(segment.text)

        if current:
            candidate_duration = segment.end - current[0].start
            candidate_words = current_words + segment_words

            exceeds_limit = (
                candidate_duration > max_seconds
                or candidate_words > max_words
            )

            if exceeds_limit:
                chunks.append(
                    TranscriptChunk(
                        chunk_id=len(chunks),
                        segments=current,
                    )
                )
                current = []
                current_words = 0

        current.append(segment)
        current_words += segment_words

    if current:
        chunks.append(
            TranscriptChunk(
                chunk_id=len(chunks),
                segments=current,
            )
        )

    return chunks


def surrounding_context(
    segments: list[WhisperSegment],
    chunk: TranscriptChunk,
    context_segments: int,
) -> tuple[str, str]:
    id_to_position = {
        segment.segment_id: position
        for position, segment in enumerate(segments)
    }

    first_position = id_to_position[chunk.segments[0].segment_id]
    last_position = id_to_position[chunk.segments[-1].segment_id]

    previous_start = max(0, first_position - context_segments)
    next_end = min(
        len(segments),
        last_position + context_segments + 1,
    )

    previous = "\n".join(
        segment.text
        for segment in segments[previous_start:first_position]
    )

    following = "\n".join(
        segment.text
        for segment in segments[last_position + 1:next_end]
    )

    return previous, following


# ---------------------------------------------------------------------------
# Ollama interaction
# ---------------------------------------------------------------------------

def build_user_prompt(
    chunk: TranscriptChunk,
    previous_context: str,
    following_context: str,
    dialect_hint: str,
    target_language: str,
) -> str:
    return f"""
Dialect hint:
{dialect_hint}

Translation target:
{target_language}

Previous context — use only to understand the passage:
{previous_context or "[none]"}

Passage to reconstruct, convert to MSA, and translate:
{chunk.raw_text}

Following context — use only to understand the passage:
{following_context or "[none]"}

Return valid structured JSON. Correct and translate only the main passage, not
the previous or following context.
""".strip()


def process_chunk(
    client: Client,
    model: str,
    chunk: TranscriptChunk,
    previous_context: str,
    following_context: str,
    dialect_hint: str,
    target_language: str,
    temperature: float,
    retries: int,
) -> SemanticOutput:
    user_prompt = build_user_prompt(
        chunk=chunk,
        previous_context=previous_context,
        following_context=following_context,
        dialect_hint=dialect_hint,
        target_language=target_language,
    )

    last_error: Exception | None = None

    for attempt in range(retries + 1):
        try:
            response = client.chat(
                model=model,
                messages=[
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT,
                    },
                    {
                        "role": "user",
                        "content": user_prompt,
                    },
                ],
                stream=False,
                think=False,
                format=SemanticOutput.model_json_schema(),
                options={
                    "temperature": temperature,
                    "num_ctx": 16384,
                },
                keep_alive="10m",
            )

            content = response.message.content

            if not content:
                raise RuntimeError("Ollama returned an empty response.")

            return SemanticOutput.model_validate_json(content)

        except (
            ResponseError,
            ValidationError,
            json.JSONDecodeError,
            RuntimeError,
        ) as exc:
            last_error = exc

            if attempt < retries:
                wait_seconds = 2 ** attempt
                print(
                    f"  Attempt {attempt + 1} failed: {exc}",
                    file=sys.stderr,
                )
                print(
                    f"  Retrying in {wait_seconds} second(s)...",
                    file=sys.stderr,
                )
                time.sleep(wait_seconds)

    raise RuntimeError(
        f"Chunk {chunk.chunk_id} failed after {retries + 1} attempts: "
        f"{last_error}"
    )


# ---------------------------------------------------------------------------
# Output
# ---------------------------------------------------------------------------

def make_chunk_record(
    chunk: TranscriptChunk,
    result: SemanticOutput,
) -> dict[str, Any]:
    return {
        "chunk_id": chunk.chunk_id,
        "segment_ids": chunk.segment_ids,
        "start": chunk.start,
        "end": chunk.end,
        "raw_transcript": chunk.raw_text,
        **result.model_dump(),
    }


def join_text(
    records: list[dict[str, Any]],
    field: str,
) -> str:
    paragraphs = [
        str(record.get(field, "")).strip()
        for record in records
        if str(record.get(field, "")).strip()
    ]

    return "\n\n".join(paragraphs).strip() + "\n"


def write_text(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8")


def write_outputs(
    input_path: Path,
    output_dir: Path,
    model: str,
    target_language: str,
    dialect_hint: str,
    records: list[dict[str, Any]],
) -> dict[str, Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    stem = input_path.stem

    semantic_path = output_dir / f"{stem}.semantic.json"
    reconstructed_path = (
        output_dir / f"{stem}.reconstructed_arabic.txt"
    )
    msa_path = output_dir / f"{stem}.msa.txt"
    translation_path = output_dir / f"{stem}.translation.txt"

    payload = {
        "source_file": str(input_path),
        "model": model,
        "target_language": target_language,
        "dialect_hint": dialect_hint,
        "summary": {
            "chunk_count": len(records),
            "review_count": sum(
                bool(record.get("needs_review"))
                for record in records
            ),
        },
        "chunks": records,
    }

    semantic_path.write_text(
        json.dumps(
            payload,
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    write_text(
        reconstructed_path,
        join_text(records, "reconstructed_arabic"),
    )

    write_text(
        msa_path,
        join_text(records, "msa"),
    )

    write_text(
        translation_path,
        join_text(records, "translation"),
    )

    return {
        "semantic": semantic_path,
        "reconstructed": reconstructed_path,
        "msa": msa_path,
        "translation": translation_path,
    }


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    args = parse_arguments()

    input_path = args.input_json.expanduser().resolve()
    output_dir = args.output_dir.expanduser().resolve()

    semantic_output = (
        output_dir / f"{input_path.stem}.semantic.json"
    )

    if semantic_output.exists() and not args.overwrite:
        print(
            f"Output already exists: {semantic_output}\n"
            "Use --overwrite to replace it.",
            file=sys.stderr,
        )
        return 1

    try:
        payload = load_json(input_path)
        segments = extract_segments(payload)

        chunks = create_chunks(
            segments=segments,
            max_seconds=args.max_seconds,
            max_words=args.max_words,
        )
    except RuntimeError as exc:
        print(f"Input error: {exc}", file=sys.stderr)
        return 1

    print(f"Input: {input_path}")
    print(f"Segments: {len(segments)}")
    print(f"Context blocks: {len(chunks)}")
    print(f"Model: {args.model}")
    print(f"Target language: {args.target_language}")

    client = Client(host=args.ollama_host)
    records: list[dict[str, Any]] = []

    for position, chunk in enumerate(chunks, start=1):
        print(
            f"\n[{position}/{len(chunks)}] "
            f"{chunk.start:.1f}s–{chunk.end:.1f}s"
        )

        previous, following = surrounding_context(
            segments=segments,
            chunk=chunk,
            context_segments=args.context_segments,
        )

        try:
            result = process_chunk(
                client=client,
                model=args.model,
                chunk=chunk,
                previous_context=previous,
                following_context=following,
                dialect_hint=args.dialect_hint,
                target_language=args.target_language,
                temperature=args.temperature,
                retries=args.retries,
            )
        except RuntimeError as exc:
            print(str(exc), file=sys.stderr)
            return 1

        record = make_chunk_record(chunk, result)
        records.append(record)

        print(
            "  Completed"
            + (" — REVIEW REQUIRED" if result.needs_review else "")
        )

        if result.uncertain_spans:
            print(
                f"  Uncertain spans: "
                f"{len(result.uncertain_spans)}"
            )

    paths = write_outputs(
        input_path=input_path,
        output_dir=output_dir,
        model=args.model,
        target_language=args.target_language,
        dialect_hint=args.dialect_hint,
        records=records,
    )

    print("\nCompleted")
    print(f"Structured data: {paths['semantic']}")
    print(f"Reconstructed:    {paths['reconstructed']}")
    print(f"MSA:              {paths['msa']}")
    print(f"Translation:      {paths['translation']}")

    review_count = sum(
        bool(record["needs_review"])
        for record in records
    )

    print(f"Blocks requiring review: {review_count}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())